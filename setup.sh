#!/bin/sh
# Writes .env with fresh secrets for this install. Run once, before
# `docker compose up --build`. Needs openssl.
set -eu
cd "$(dirname "$0")"

if [ -f .env ]; then
    echo ".env already exists; delete it first to generate new secrets."
    exit 0
fi
command -v openssl >/dev/null || { echo "openssl is needed"; exit 1; }

key=$(mktemp)
trap 'rm -f "$key"' EXIT
openssl genpkey -algorithm RSA -pkeyopt rsa_keygen_bits:2048 -out "$key" 2>/dev/null
b64() { openssl base64 -A; }

{
    echo "# Generated by setup.sh on $(date -u +%Y-%m-%d). Never commit this file."
    echo "DEMO_JWT_PRIVATE_KEY=$(b64 < "$key")"
    echo "DEMO_JWT_PUBLIC_KEY=$(openssl pkey -in "$key" -pubout 2>/dev/null | b64)"
    echo "PAYMENT_WEBHOOK_SECRET=$(openssl rand -hex 32)"
    echo "BFF_FORWARDING_KEY=$(openssl rand -hex 32)"
} > .env
chmod 600 .env
echo "Wrote .env. Next: docker compose up --build, then open http://localhost:3000"
